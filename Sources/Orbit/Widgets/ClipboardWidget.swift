import AppKit
import SwiftUI

// Milestone 8: clipboard history and a quick note (Sapphire parity).

/// One copied text or link.
struct ClipboardItem: Identifiable, Equatable, Sendable {
    let id = UUID()
    let text: String
    let copiedAt: Date
    var isLink: Bool { text.hasPrefix("http://") || text.hasPrefix("https://") }
}

/// Clipboard history: **off by default**, in memory only (cleared when Orbit
/// quits; clipboards hold passwords and private text, so nothing goes to
/// disk). Watches the pasteboard's change count every 1.5 s only while on;
/// skips items apps mark as concealed or transient (password managers do,
/// per nspasteboard.org) and anything over 20,000 characters.
@MainActor @Observable
final class ClipboardHistory {
    static let shared = ClipboardHistory()
    static let limit = 40
    static let maxLength = 20_000
    /// The nspasteboard.org markers: never recorded.
    static let privateTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                                            "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    private(set) var items: [ClipboardItem] = []
    private(set) var isOn = false
    @ObservationIgnored private var lastChange = 0
    @ObservationIgnored private var timer: Task<Void, Never>?
    @ObservationIgnored private let read: @MainActor () -> (change: Int, text: String?, types: Set<String>)
    @ObservationIgnored private let write: @MainActor (String) -> Int
    @ObservationIgnored private let clock: () -> Date

    init(read: @escaping @MainActor () -> (change: Int, text: String?, types: Set<String>) = ClipboardHistory.systemRead,
         write: @escaping @MainActor (String) -> Int = ClipboardHistory.systemWrite, clock: @escaping () -> Date = { .now }) {
        self.read = read
        self.write = write
        self.clock = clock
    }

    static func systemRead() -> (change: Int, text: String?, types: Set<String>) {
        let board = NSPasteboard.general
        return (board.changeCount, board.string(forType: .string), Set((board.types ?? []).map(\.rawValue)))
    }

    static func systemWrite(_ text: String) -> Int {
        let board = NSPasteboard.general
        board.clearContents()
        board.setString(text, forType: .string)
        return board.changeCount
    }

    func setOn(_ on: Bool) {
        guard on != isOn else { return }
        isOn = on
        timer?.cancel()
        timer = nil
        guard on else { items = []; return }  // off forgets everything
        lastChange = read().change  // what's on the clipboard now isn't "history"
        timer = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(1500), tolerance: .milliseconds(500))
                self?.poll()
            }
        }
    }

    func poll() {
        let now = read()
        guard isOn, now.change != lastChange else { return }
        lastChange = now.change
        guard now.types.isDisjoint(with: Self.privateTypes), let text = now.text,
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= Self.maxLength else { return }
        items.removeAll { $0.text == text }  // copied again: moves to the top
        items.insert(ClipboardItem(text: text, copiedAt: clock()), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
    }

    /// Puts an item back on the clipboard (and at the top), without recording it twice.
    func copy(_ item: ClipboardItem) {
        lastChange = write(item.text)
        items.removeAll { $0.id == item.id }
        items.insert(ClipboardItem(text: item.text, copiedAt: clock()), at: 0)
    }

    func remove(_ item: ClipboardItem) { items.removeAll { $0.id == item.id } }
    func clear() { items = [] }
}

@MainActor
final class ClipboardWidget: DashboardWidget {
    let metadata = WidgetMetadata(
        id: "clipboard", title: "Clipboard", description: "Recent copied text and links (off until you turn it on)",
        symbol: "doc.on.clipboard", category: .productivity, availability: .live,
        presentations: [.compact, .expanded], sectionPresentation: .expanded, isEnabledByDefault: false)
    let history: ClipboardHistory
    var state: WidgetState { .ready }

    init(history: ClipboardHistory = .shared) { self.history = history }

    func content(_ presentation: WidgetPresentation) -> AnyView {
        AnyView(ClipboardView(history: history, compact: presentation == .compact))
    }
}

private struct ClipboardView: View {
    let history: ClipboardHistory
    let compact: Bool

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack(spacing: 8) {
                OrbitSwitch(label: "Clipboard history", isOn: history.isOn, set: history.setOn)
                Text(history.isOn ? "Recording copies" : "Off").font(OrbitType.caption).foregroundStyle(Theme.secondary)
                Spacer()
                if !history.items.isEmpty { OrbitLinkButton(title: "Clear", action: history.clear) }
            }
            if !history.isOn {
                Text("Keeps your last \(ClipboardHistory.limit) copied texts and links in memory only, never on disk. Passwords that apps mark as private are skipped.")
                    .font(OrbitType.caption).foregroundStyle(Theme.tertiary).fixedSize(horizontal: false, vertical: true)
            } else if history.items.isEmpty {
                StatusMessage(text: "Copy something to see it here.", symbol: "doc.on.clipboard")
            } else {
                HubScroll {
                    VStack(spacing: 3) {
                        ForEach(compact ? Array(history.items.prefix(4)) : history.items) { item in
                            Button { history.copy(item) } label: {
                                HStack(spacing: 7) {
                                    Image(systemName: item.isLink ? "link" : "text.alignleft").foregroundStyle(Theme.tertiary).frame(width: 14)
                                    Text(item.text.replacingOccurrences(of: "\n", with: " ")).lineLimit(1).truncationMode(.middle)
                                    Spacer(minLength: 4)
                                    Text(item.copiedAt, format: .relative(presentation: .named, unitsStyle: .abbreviated))
                                        .font(OrbitType.caption).foregroundStyle(Theme.tertiary).fixedSize()
                                }
                                .font(.system(size: 11.5, weight: .medium))
                                .padding(.horizontal, 8).padding(.vertical, 5)
                                .orbitSurface(radius: 8)
                                .contentShape(.rect)
                            }
                            .buttonStyle(DashboardButtonStyle())
                            .help("Copy again")
                            .accessibilityLabel("Copy again: \(item.text.prefix(80))")
                            .contextMenu { Button("Remove") { history.remove(item) } }
                        }
                    }
                }
            }
        }
    }
}

// MARK: Quick Note

/// One always-there scratch note, saved as you type (quicknote.json).
@MainActor @Observable
final class QuickNoteWidget: DashboardWidget {
    let metadata = WidgetMetadata(
        id: "quickNote", title: "Quick Note", description: "A scratch note that saves as you type",
        symbol: "note.text", category: .productivity, availability: .live,
        presentations: [.compact, .expanded], isEnabledByDefault: false)
    private var stored: Persisted<String>
    @ObservationIgnored private var saveTask: Task<Void, Never>?
    @ObservationIgnored private let saveDelay: Duration

    init(file: JSONFile<String>?, saveDelay: Duration = .milliseconds(600)) {
        let stored = file.map { Persisted($0, initial: "") } ?? Persisted(memory: "")
        self.stored = stored
        self.saveDelay = saveDelay
        text = stored.value
    }

    /// What's on screen; saved shortly after typing pauses (and when hidden).
    var text: String {
        didSet {
            guard text != oldValue else { return }
            saveTask?.cancel()
            saveTask = Task { [weak self, saveDelay] in
                try? await Task.sleep(for: saveDelay)
                guard !Task.isCancelled else { return }
                self?.save()
            }
        }
    }

    var state: WidgetState { stored.problem.map(WidgetState.failed) ?? .ready }

    func stop() { save() }

    func save() {
        saveTask?.cancel()
        saveTask = nil
        guard stored.value != text else { return }
        let current = text
        stored.update { $0 = current }
    }

    func content(_ presentation: WidgetPresentation) -> AnyView {
        AnyView(VStack(alignment: .leading, spacing: 4) {
            TextEditor(text: Binding(get: { self.text }, set: { self.text = $0 }))
                .font(.system(size: 12))
                .scrollContentBackground(.hidden)
                .padding(6)
                .orbitSurface(radius: 10)
                .accessibilityLabel("Quick note")
            Text("\(text.count) characters · saved on this Mac").font(OrbitType.caption).foregroundStyle(Theme.tertiary)
        })
    }
}
